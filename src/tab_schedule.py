"""Paper table: classical and gain-scheduled circuits (hyper_m.py, option AB, joint, 20000 steps), from results/runs.jsonl. Mean test SRE / NERE over
the 15 materials and the official average 95th-percentile SRE / NERE on the five final-evaluation materials; mean ± standard
deviation over the seeds that are complete (their number in brackets), pending runs as "…".
Usage: python tab_schedule.py   -> paper/tables/schedule.typ"""
from mc2lib import ROOT
from runlog import table

SEEDS = lambda base, first, n=10: [first] + [f"{base}_s{s}" for s in range(1, n)]
NSCHED = 10  # seeds of the scheduled circuits used (0 .. NSCHED-1): 5 in arXiv v1, 10 since v2
ROWS = [  # (label, h, names, variant): classical circuit and the scheduled circuits (option AB, joint, 20000 steps)
    ("classical", "–", SEEDS("ne", "nere"), "final_e1"),
    ("MLP16-scheduled", 16, SEEDS("hyAB16j", "hyAB16j_long", NSCHED), "final_e1+hyperAB16j"),
    ("MLP64-scheduled", 64, SEEDS("hyAB64j", "hyAB64j_s0", NSCHED), "final_e1+hyperAB64j"),
]
COLS = ["test_sre_mean", "test_nere_mean", "off_sre_p95", "off_nere_p95"]

t = table()
out = ["// generated by src/tab_schedule.py from results/runs.jsonl", "#figure(", "  table(",
       "    columns: 7, align: (left, center, right, right, right, right, right), stroke: none,", "    table.hline(),",
       "    table.header([*Circuit*], [$h$], [*Param.*], table.cell(colspan: 2)[*Mean test*], table.cell(colspan: 2)[*Official p95*]),",
       "    [], [], [], [SRE], [NERE], [SRE], [NERE],", "    table.hline(),"]
for o, h, names, var in ROWS:
    d = t[t.name.isin(names) & (t.variant == var)].dropna(subset=["test_sre_mean"])
    npar = int(d.params_per_mat.iloc[0]) if len(d) else {"–": 32, 16: 656, 64: 5552}[h]          # pending: option AB sizes
    cells = []
    for c in COLS:
        v = d[c].dropna().to_numpy()
        cells.append("…" if not len(v) else f"{v.mean():.2f}" if len(v) == 1 else f"{v.mean():.2f} ± {v.std(ddof=1):.2f}")
    out.append(f"    [{o} ({len(d)})], [{h}], [{npar}], " + ", ".join(f"[{c}]" for c in cells) + ",")
out += ["    table.hline(),", "  ),",
        "  caption: [Classical and gain-scheduled circuits (scheduled: reversible curve, hysteresis gain and operator dynamics,"
        " trained jointly with the 32 circuit parameters, 20 000 steps): hidden units $h$, parameters per material (without the 33 of the"
        " warm-up estimator, @sec:observer, which all three circuits share), mean test"
        " SRE and NERE in % over the 15 materials, and the official average 95th-percentile SRE and energy error in % on the"
        " five final-evaluation materials. Mean ± standard deviation over the number of training seeds in brackets.],",
"  placement: top, scope: \"parent\",", ") <tab:schedule>"]
(ROOT / "paper/tables/schedule.typ").write_text("\n".join(out) + "\n")
print("\n".join(out))
